// ---------- rng / math helpers ----------

function mulberry32(a: number) {
  return function () {
    let t = (a += 0x6d2b79f5);
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function randn(rng: () => number): number {
  let u = 0,
    v = 0;
  while (u === 0) u = rng();
  while (v === 0) v = rng();
  return Math.sqrt(-2.0 * Math.log(u)) * Math.cos(2.0 * Math.PI * v);
}

function cloneMatrix(m: Matrix): Matrix {
  return m.map((row) => row.slice());
}

function matVec(M: Matrix, v: Vec): Vec {
  return M.map((row) => row.reduce((sum, w, i) => sum + w * v[i], 0));
}

function mse(pred: Vec, target: Vec): number {
  let s = 0;
  for (let i = 0; i < pred.length; i++) {
    const d = pred[i] - target[i];
    s += d * d;
  }
  return s / pred.length;
}

export function maxAbs(arr: Vec): number {
  return Math.max(...arr.map((v) => Math.abs(v)), 1e-9);
}

export function flatten2D(m: Matrix): Vec {
  return m.flat();
}

function computeGradient(batchX: Matrix, batchY: Matrix, W: Matrix): Matrix {
  const grad = Array.from({ length: OUTPUT_DIM }, () => Array(INPUT_DIM).fill(0));
  const scale = 2 / (batchX.length * OUTPUT_DIM);
  for (let b = 0; b < batchX.length; b++) {
    const pred = matVec(W, batchX[b]);
    for (let o = 0; o < OUTPUT_DIM; o++) {
      const err = pred[o] - batchY[b][o];
      for (let i = 0; i < INPUT_DIM; i++) grad[o][i] += scale * err * batchX[b][i];
    }
  }
  return grad;
}

function fullLoss(W: Matrix, X: Matrix, Y: Matrix): number {
  let total = 0;
  for (let n = 0; n < X.length; n++) total += mse(matVec(W, X[n]), Y[n]);
  return total / X.length;
}

function shuffleIndices(n: number, rng: () => number): number[] {
  const arr = Array.from({ length: n }, (_, i) => i);
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

// The nonlinearity that generates the target data. The lifted models use this
// exact function as their activation, so they can in principle match the data.
export function dataNonlinearity(v: number): number {
  const primary = Math.tanh(NONLIN_SCALE * v);
  const harmonic = NONLIN_HARMONIC * Math.sin(5.5 * v + 0.35);
  const tertiary = NONLIN_TERTIARY * Math.sin(11.0 * v * v);
  return primary + harmonic + tertiary;
}

// φ'(v), used to backprop through the activation.
export function dataNonlinearityDeriv(v: number): number {
  const t = Math.tanh(NONLIN_SCALE * v);
  const dPrimary = NONLIN_SCALE * (1 - t * t);
  const dHarmonic = NONLIN_HARMONIC * 5.5 * Math.cos(5.5 * v + 0.35);
  const dTertiary = NONLIN_TERTIARY * Math.cos(11.0 * v * v) * 22.0 * v;
  return dPrimary + dHarmonic + dTertiary;
}

function buildDataset(rng: () => number) {
  const secretW: Matrix = [
    [1.6, -0.9, 0.4, 0.1],
    [-0.7, 1.3, -1.1, 0.6],
    [0.2, -0.4, 1.8, -0.8],
    [1.0, 0.5, -0.6, 1.1],
  ];
  const X = Array.from({ length: DATASET_SIZE }, () =>
    Array.from({ length: INPUT_DIM }, () => randn(rng) * 1.15)
  );
  const nonlinearY = X.map((x) => matVec(secretW, x).map(dataNonlinearity));
  const initW = Array.from({ length: OUTPUT_DIM }, () =>
    Array.from({ length: INPUT_DIM }, () => randn(rng) * 0.85)
  );
  return { X, nonlinearY, initW };
}

function createEpochOrders(): number[][] {
  const rng = mulberry32(SEED + 101);
  const orders: number[][] = [];
  for (let epoch = 0; epoch < EPOCHS; epoch++) orders.push(shuffleIndices(DATASET_SIZE, rng));
  return orders;
}

function buildFrames(targets: Matrix, initW: Matrix, epochOrders: number[][], X: Matrix): Frame[] {
  const W = cloneMatrix(initW);
  let m = Array.from({ length: OUTPUT_DIM }, () => Array(INPUT_DIM).fill(0));
  let v = Array.from({ length: OUTPUT_DIM }, () => Array(INPUT_DIM).fill(0));
  const frames: Frame[] = [];
  let step = 0;

  for (let epoch = 0; epoch < EPOCHS; epoch++) {
    const order = epochOrders[epoch];
    for (let batchStart = 0; batchStart < DATASET_SIZE; batchStart += BATCH_SIZE) {
      const batchIndices = order.slice(batchStart, batchStart + BATCH_SIZE);
      const batchX = batchIndices.map((i) => X[i]);
      const batchY = batchIndices.map((i) => targets[i]);
      const batchGrad = computeGradient(batchX, batchY, W);
      const batchLoss =
        batchIndices.reduce((sum, i) => sum + mse(matVec(W, X[i]), targets[i]), 0) /
        batchIndices.length;
      const lossBeforeUpdate = fullLoss(W, X, targets);
      const gradNorm = Math.sqrt(flatten2D(batchGrad).reduce((sum, g) => sum + g * g, 0));

      const nextM = cloneMatrix(m);
      const nextV = cloneMatrix(v);
      const adamStep = step + 1;
      const beta1Pow = Math.pow(BETA1, adamStep);
      const beta2Pow = Math.pow(BETA2, adamStep);
      for (let i = 0; i < OUTPUT_DIM; i++) {
        for (let j = 0; j < INPUT_DIM; j++) {
          const g = batchGrad[i][j];
          nextM[i][j] = BETA1 * nextM[i][j] + (1 - BETA1) * g;
          nextV[i][j] = BETA2 * nextV[i][j] + (1 - BETA2) * g * g;
        }
      }

      frames.push({
        step,
        epoch,
        batchInEpoch: batchStart / BATCH_SIZE,
        batchIndices,
        W: cloneMatrix(W),
        grad: cloneMatrix(batchGrad),
        m: cloneMatrix(nextM),
        v: cloneMatrix(nextV),
        dataBatchLoss: batchLoss,
        dataFullLoss: lossBeforeUpdate,
        l1Penalty: 0,
        batchLoss,
        fullLoss: lossBeforeUpdate,
        gradNorm,
      });

      for (let i = 0; i < OUTPUT_DIM; i++) {
        for (let j = 0; j < INPUT_DIM; j++) {
          const mHat = nextM[i][j] / (1 - beta1Pow);
          const vHat = nextV[i][j] / (1 - beta2Pow);
          W[i][j] -= (LR * mHat) / (Math.sqrt(vHat) + ADAM_EPS);
        }
      }
      m = nextM;
      v = nextV;
      step += 1;
    }
  }
  return frames;
}

// ---------- sparse-routing linear algebra ----------

function transposeMatrix(M: Matrix): Matrix {
  return M[0].map((_, j) => M.map((row) => row[j]));
}

function zeroMatrix(size: number): Matrix {
  return Array.from({ length: size }, () => Array(size).fill(0));
}

function orthonormalizeColumns(matrix: Matrix): Matrix | null {
  const rows = matrix.length;
  const cols = matrix[0].length;
  const q = Array.from({ length: rows }, () => Array(cols).fill(0));
  for (let col = 0; col < cols; col++) {
    const v = matrix.map((row) => row[col]);
    for (let prev = 0; prev < col; prev++) {
      const qprev = q.map((row) => row[prev]);
      let proj = 0;
      for (let i = 0; i < rows; i++) proj += v[i] * qprev[i];
      for (let i = 0; i < rows; i++) v[i] -= proj * qprev[i];
    }
    let norm = 0;
    for (let i = 0; i < rows; i++) norm += v[i] * v[i];
    norm = Math.sqrt(norm);
    if (!isFinite(norm) || norm < 1e-12) return null;
    for (let i = 0; i < rows; i++) q[i][col] = v[i] / norm;
  }
  return q;
}

const SPARSE_INIT_SCALE = 0.5; // std-dev of the random initial active weights

function buildSparseRouting(rng: () => number): Routing {
  let up: Matrix | null = null;
  while (!up) {
    const raw = Array.from({ length: SPARSE_DIM }, () =>
      Array.from({ length: INPUT_DIM }, () => randn(rng))
    );
    up = orthonormalizeColumns(raw);
  }
  const down = transposeMatrix(up);

  // Pick ACTIVE_COUNT random distinct cells anywhere in the 16×16 scaffold and
  // initialise them with small random weights (0 everywhere else).
  const positions: [number, number][] = [];
  const positionSet = new Set<string>();
  const initW = zeroMatrix(SPARSE_DIM);
  while (positions.length < ACTIVE_COUNT) {
    const r = Math.floor(rng() * SPARSE_DIM);
    const c = Math.floor(rng() * SPARSE_DIM);
    const key = `${r}:${c}`;
    if (positionSet.has(key)) continue;
    positionSet.add(key);
    positions.push([r, c]);
    initW[r][c] = randn(rng) * SPARSE_INIT_SCALE;
  }
  return { up, down, positions, positionSet, initW };
}

function sparseLift(x: Vec, routing: Routing): Vec {
  return matVec(routing.up, x);
}

// Nonlinear lifted model: pred = Uᵀ · φ(W · (U · x)), where φ is the SAME
// nonlinearity that generated the target data. This makes the model genuinely
// nonlinear (a 1-hidden-layer net with fixed lift/unlift) and lets it fit the
// target beyond the rank-4 ceiling of the purely linear version.
export function sparsePredict(
  W: Matrix,
  x: Vec,
  routing: Routing
): { lifted: Vec; pre: Vec; act: Vec; pred: Vec } {
  const lifted = sparseLift(x, routing); // z = U·x
  const pre = matVec(W, lifted); // a = W·z
  const act = pre.map(dataNonlinearity); // h = φ(a)
  return { lifted, pre, act, pred: matVec(routing.down, act) };
}

function fullLossSparse(W: Matrix, X: Matrix, Y: Matrix, routing: Routing): number {
  let total = 0;
  for (let n = 0; n < X.length; n++) total += mse(sparsePredict(W, X[n], routing).pred, Y[n]);
  return total / X.length;
}

function sparseL1Penalty(W: Matrix, active: [number, number][]): number {
  let sumAbs = 0;
  for (const [r, c] of active) sumAbs += Math.abs(W[r][c]);
  return SPARSE_L1 * (sumAbs / active.length);
}

function sparseL1Gradient(W: Matrix, active: [number, number][]): Matrix {
  const grad = zeroMatrix(SPARSE_DIM);
  const scale = SPARSE_L1 / active.length;
  for (const [r, c] of active) grad[r][c] = scale * Math.sign(W[r][c]);
  return grad;
}

// Dense data gradient (all 16×16 cells) + mean data loss for one mini-batch.
// The gradient at an *inactive* cell (i,j) is still meaningful: it equals the
// accumulated back[i]·lifted[j], i.e. how much the loss would move if that cell
// were allowed to change. That is the "where could error be lowered most" signal.
function sparseDataGradAndLoss(
  batchIndices: number[],
  X: Matrix,
  targets: Matrix,
  W: Matrix,
  routing: Routing
): { grad: Matrix; dataLoss: number } {
  const grad = zeroMatrix(SPARSE_DIM);
  let dataLoss = 0;
  const scale = 2 / (batchIndices.length * OUTPUT_DIM);
  for (const idx of batchIndices) {
    const { lifted, pre, pred } = sparsePredict(W, X[idx], routing);
    dataLoss += mse(pred, targets[idx]);
    const err = pred.map((val, i) => val - targets[idx][i]);
    // ∂L/∂h = U·err ; backprop through φ: ∂L/∂a = ∂L/∂h ⊙ φ'(a)
    const back = matVec(routing.up, err);
    for (let i = 0; i < SPARSE_DIM; i++) {
      const delta = back[i] * dataNonlinearityDeriv(pre[i]);
      for (let j = 0; j < SPARSE_DIM; j++) grad[i][j] += scale * delta * lifted[j];
    }
  }
  return { grad, dataLoss: dataLoss / batchIndices.length };
}

// Grow: the inactive cell with the largest |gradient|. Because the sample
// gradient separates as back[i]·lifted[j], this is exactly the (highest error
// component, highest input activation) coordinate the batch points to.
function chooseGrow(grad: Matrix, activeSet: Set<string>): [number, number] | null {
  let best: [number, number] | null = null;
  let bestScore = -1;
  for (let i = 0; i < SPARSE_DIM; i++)
    for (let j = 0; j < SPARSE_DIM; j++) {
      if (activeSet.has(`${i}:${j}`)) continue;
      const s = Math.abs(grad[i][j]);
      if (s > bestScore) {
        bestScore = s;
        best = [i, j];
      }
    }
  return best;
}

// Thresholds (fractions of the active-set maxima) below which a cell counts as
// "near zero" / "stable" and is therefore safe to prune without jolting output.
const PRUNE_W_FRAC = 0.35;
const PRUNE_M_FRAC = 0.4;
const PRUNE_G_FRAC = 0.6;

interface PruneChoice {
  pos: [number, number];
  wRatio: number; // |W| relative to active max  → "near zero"
  mRatio: number; // |m| relative to active max  → momentum "stability"
  gRatio: number; // |grad| relative to active max → gradient "stability"
}

// Prune: the active cell that is most "dead" — small weight AND stable, i.e.
// small first-moment (momentum) AND small gradient. Each signal is normalized
// by the active-set max so the three contribute on a comparable scale, and we
// keep the ratios so the caller can require the cell is genuinely near-zero.
function choosePrune(
  W: Matrix,
  m: Matrix,
  grad: Matrix,
  active: [number, number][]
): PruneChoice | null {
  let maxW = 1e-9;
  let maxM = 1e-9;
  let maxG = 1e-9;
  for (const [r, c] of active) {
    maxW = Math.max(maxW, Math.abs(W[r][c]));
    maxM = Math.max(maxM, Math.abs(m[r][c]));
    maxG = Math.max(maxG, Math.abs(grad[r][c]));
  }
  let best: PruneChoice | null = null;
  let bestScore = Infinity;
  for (const [r, c] of active) {
    const wRatio = Math.abs(W[r][c]) / maxW;
    const mRatio = Math.abs(m[r][c]) / maxM;
    const gRatio = Math.abs(grad[r][c]) / maxG;
    const dead = wRatio + mRatio + gRatio;
    if (dead < bestScore) {
      bestScore = dead;
      best = { pos: [r, c], wRatio, mRatio, gRatio };
    }
  }
  return best;
}

// A prune candidate is safe only if it is near-zero AND stable in both senses.
function isSafeToPrune(p: PruneChoice): boolean {
  return p.wRatio < PRUNE_W_FRAC && p.mRatio < PRUNE_M_FRAC && p.gRatio < PRUNE_G_FRAC;
}

function buildSparseFrames(
  targets: Matrix,
  epochOrders: number[][],
  X: Matrix,
  routing: Routing
): Frame[] {
  const W = cloneMatrix(routing.initW);
  let m = zeroMatrix(SPARSE_DIM);
  let v = zeroMatrix(SPARSE_DIM);
  const frames: Frame[] = [];
  let step = 0;

  // The active (trainable) cells start on the basis block but can move.
  const activeSet = new Set(routing.positions.map(([r, c]) => `${r}:${c}`));
  let activeList: [number, number][] = routing.positions.map(([r, c]) => [r, c]);

  for (let epoch = 0; epoch < EPOCHS; epoch++) {
    const order = epochOrders[epoch];
    for (let batchStart = 0; batchStart < DATASET_SIZE; batchStart += BATCH_SIZE) {
      const batchIndices = order.slice(batchStart, batchStart + BATCH_SIZE);

      // --- grow-and-prune once per epoch (after a one-epoch warm-up so Adam's
      //     moments are informative) ---
      let grown: [number, number] | null = null;
      let pruned: [number, number] | null = null;
      if (epoch >= 1 && batchStart === 0) {
        const probe = sparseDataGradAndLoss(batchIndices, X, targets, W, routing);
        const growCand = chooseGrow(probe.grad, activeSet);
        const pruneCand = choosePrune(W, m, probe.grad, activeList);
        // Only swap when the prune target is genuinely near-zero and stable, and
        // the grow target is more promising (larger gradient) than what we drop.
        if (
          growCand &&
          pruneCand &&
          isSafeToPrune(pruneCand) &&
          Math.abs(probe.grad[growCand[0]][growCand[1]]) >
            Math.abs(probe.grad[pruneCand.pos[0]][pruneCand.pos[1]])
        ) {
          grown = growCand;
          pruned = pruneCand.pos;
          const [pr, pc] = pruned;
          const [gr, gc] = grown;
          activeSet.delete(`${pr}:${pc}`);
          activeSet.add(`${gr}:${gc}`);
          activeList = activeList.filter(([a, b]) => !(a === pr && b === pc));
          activeList.push([gr, gc]);
          // prune: drop the weight and its optimizer state
          W[pr][pc] = 0;
          m[pr][pc] = 0;
          v[pr][pc] = 0;
          // grow: initialise at zero so the prediction is unchanged at the swap
          W[gr][gc] = 0;
          m[gr][gc] = 0;
          v[gr][gc] = 0;
        } else {
          grown = null;
          pruned = null;
        }
      }

      // --- normal Adam step on the current active set ---
      const { grad: batchGrad, dataLoss: dataBatchLoss } = sparseDataGradAndLoss(
        batchIndices,
        X,
        targets,
        W,
        routing
      );
      const dataFullLoss = fullLossSparse(W, X, targets, routing);
      const l1Penalty = sparseL1Penalty(W, activeList);
      const regGrad = sparseL1Gradient(W, activeList);
      for (const [r, c] of activeList) batchGrad[r][c] += regGrad[r][c];
      const batchLoss = dataBatchLoss + l1Penalty;
      const frameFullLoss = dataFullLoss + l1Penalty;
      let gradSq = 0;
      for (const [r, c] of activeList) gradSq += batchGrad[r][c] * batchGrad[r][c];
      const gradNorm = Math.sqrt(gradSq);

      const nextM = cloneMatrix(m);
      const nextV = cloneMatrix(v);
      const adamStep = step + 1;
      const beta1Pow = Math.pow(BETA1, adamStep);
      const beta2Pow = Math.pow(BETA2, adamStep);
      for (const [r, c] of activeList) {
        const g = batchGrad[r][c];
        nextM[r][c] = BETA1 * nextM[r][c] + (1 - BETA1) * g;
        nextV[r][c] = BETA2 * nextV[r][c] + (1 - BETA2) * g * g;
      }

      frames.push({
        step,
        epoch,
        batchInEpoch: batchStart / BATCH_SIZE,
        batchIndices,
        W: cloneMatrix(W),
        grad: cloneMatrix(batchGrad),
        m: cloneMatrix(nextM),
        v: cloneMatrix(nextV),
        dataBatchLoss,
        dataFullLoss,
        l1Penalty,
        batchLoss,
        fullLoss: frameFullLoss,
        gradNorm,
        activePositions: activeList.map(([r, c]) => [r, c] as [number, number]),
        grown,
        pruned,
      });

      for (const [r, c] of activeList) {
        const mHat = nextM[r][c] / (1 - beta1Pow);
        const vHat = nextV[r][c] / (1 - beta2Pow);
        W[r][c] -= (LR * mHat) / (Math.sqrt(vHat) + ADAM_EPS);
      }
      m = nextM;
      v = nextV;
      step += 1;
    }
  }
  return frames;
}

// Dense baseline: same fixed lift/unlift, but every one of the 256 scaffold
// cells is trainable. No sparsity, no grow-and-prune, no L1.
function buildDenseScaffoldFrames(
  targets: Matrix,
  epochOrders: number[][],
  X: Matrix,
  routing: Routing,
  initW: Matrix
): Frame[] {
  const W = cloneMatrix(initW);
  let m = zeroMatrix(SPARSE_DIM);
  let v = zeroMatrix(SPARSE_DIM);
  const frames: Frame[] = [];
  let step = 0;

  for (let epoch = 0; epoch < EPOCHS; epoch++) {
    const order = epochOrders[epoch];
    for (let batchStart = 0; batchStart < DATASET_SIZE; batchStart += BATCH_SIZE) {
      const batchIndices = order.slice(batchStart, batchStart + BATCH_SIZE);
      const { grad: batchGrad, dataLoss: dataBatchLoss } = sparseDataGradAndLoss(
        batchIndices,
        X,
        targets,
        W,
        routing
      );
      const dataFullLoss = fullLossSparse(W, X, targets, routing);
      let gradSq = 0;
      for (let i = 0; i < SPARSE_DIM; i++)
        for (let j = 0; j < SPARSE_DIM; j++) gradSq += batchGrad[i][j] * batchGrad[i][j];
      const gradNorm = Math.sqrt(gradSq);

      const nextM = cloneMatrix(m);
      const nextV = cloneMatrix(v);
      const adamStep = step + 1;
      const beta1Pow = Math.pow(BETA1, adamStep);
      const beta2Pow = Math.pow(BETA2, adamStep);
      for (let i = 0; i < SPARSE_DIM; i++)
        for (let j = 0; j < SPARSE_DIM; j++) {
          const g = batchGrad[i][j];
          nextM[i][j] = BETA1 * nextM[i][j] + (1 - BETA1) * g;
          nextV[i][j] = BETA2 * nextV[i][j] + (1 - BETA2) * g * g;
        }

      frames.push({
        step,
        epoch,
        batchInEpoch: batchStart / BATCH_SIZE,
        batchIndices,
        W: cloneMatrix(W),
        grad: cloneMatrix(batchGrad),
        m: cloneMatrix(nextM),
        v: cloneMatrix(nextV),
        dataBatchLoss,
        dataFullLoss,
        l1Penalty: 0,
        batchLoss: dataBatchLoss,
        fullLoss: dataFullLoss,
        gradNorm,
      });

      for (let i = 0; i < SPARSE_DIM; i++)
        for (let j = 0; j < SPARSE_DIM; j++) {
          const mHat = nextM[i][j] / (1 - beta1Pow);
          const vHat = nextV[i][j] / (1 - beta2Pow);
          W[i][j] -= (LR * mHat) / (Math.sqrt(vHat) + ADAM_EPS);
        }
      m = nextM;
      v = nextV;
      step += 1;
    }
  }
  return frames;
}

export function matVecPublic(M: Matrix, v: Vec): Vec {
  return matVec(M, v);
}
export function msePublic(pred: Vec, target: Vec): number {
  return mse(pred, target);
}

// Build both simulations once. Deterministic (seeded), so server and client agree.
export function buildSimulations(): Record<Mode, Simulation> {
  const dataset = buildDataset(mulberry32(SEED));
  const epochOrders = createEpochOrders();
  const sparseRouting = buildSparseRouting(mulberry32(SEED + SPARSE_ROUTING_SEED));
  // full random 16×16 init for the dense baseline (its own seed)
  const denseRng = mulberry32(SEED + 555);
  const denseInit = Array.from({ length: SPARSE_DIM }, () =>
    Array.from({ length: SPARSE_DIM }, () => randn(denseRng) * SPARSE_INIT_SCALE)
  );
  return {
    nonlinear: {
      frames: buildFrames(dataset.nonlinearY, dataset.initW, epochOrders, dataset.X),
      targets: dataset.nonlinearY,
      X: dataset.X,
    },
    sparse: {
      frames: buildSparseFrames(dataset.nonlinearY, epochOrders, dataset.X, sparseRouting),
      targets: dataset.nonlinearY,
      X: dataset.X,
      routing: sparseRouting,
    },
    dense16: {
      frames: buildDenseScaffoldFrames(
        dataset.nonlinearY,
        epochOrders,
        dataset.X,
        sparseRouting,
        denseInit
      ),
      targets: dataset.nonlinearY,
      X: dataset.X,
      routing: sparseRouting,
    },
  };
}
