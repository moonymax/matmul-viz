// Simulation for the interactive 4×4 matrix-training demo.
// Two modes share one hidden "secret" matrix and a nonlinear target:
//   - nonlinear: a plain 4×4 linear model trained with Adam
//   - sparse:    the same model reparameterized onto a 16×16 scaffold with a
//                fixed dense lift/down routing and an L1 penalty.
// Everything is precomputed into `frames` so the UI can scrub through training.

export type Matrix = number[][];
export type Vec = number[];

export const INPUT_DIM = 4;
export const OUTPUT_DIM = 4;
export const DATASET_SIZE = 64;
export const BATCH_SIZE = 8;
export const EPOCHS = 25;
export const LR = 0.04;
const BETA1 = 0.9;
const BETA2 = 0.999;
const ADAM_EPS = 1e-8;
const SEED = 17;
const NONLIN_SCALE = 2.85;
const NONLIN_HARMONIC = 0.55;
const NONLIN_TERTIARY = 0.18;
export const SPARSE_DIM = 16;
const SPARSE_ROUTING_SEED = 91;
const SPARSE_L1 = 0.08;
// The scaffold basis contributes 4×4 = 16 trainable cells; EXTRA_ACTIVE adds
// more movable weights on top. ACTIVE_COUNT is held constant by grow-and-prune.
export const EXTRA_ACTIVE = 2;
export const ACTIVE_COUNT = 16 + EXTRA_ACTIVE;

export interface Frame {
  step: number;
  epoch: number;
  batchInEpoch: number;
  batchIndices: number[];
  W: Matrix;
  grad: Matrix;
  m: Matrix;
  v: Matrix;
  dataBatchLoss: number;
  dataFullLoss: number;
  l1Penalty: number;
  batchLoss: number;
  fullLoss: number;
  gradNorm: number;
  // dynamic-sparse bookkeeping (sparse mode only)
  activePositions?: [number, number][];
  grown?: [number, number] | null;
  pruned?: [number, number] | null;
}

export interface Routing {
  up: Matrix;
  down: Matrix;
  positions: [number, number][]; // random initial active cells
  positionSet: Set<string>;
  initW: Matrix; // 16×16, random values at `positions`, zero elsewhere
}

export interface Simulation {
  frames: Frame[];
  targets: Matrix;
  X: Matrix;
  routing?: Routing;
}

